//go:build !windows

package tern

import (
	"os"
	"syscall"
)

// setBlocking clears O_NONBLOCK on f.
func setBlocking(f *os.File) error {
	rc, err := f.SyscallConn()
	if err != nil {
		return err
	}
	var serr error
	if err := rc.Control(func(fd uintptr) { serr = syscall.SetNonblock(int(fd), false) }); err != nil {
		return err
	}
	return serr
}
