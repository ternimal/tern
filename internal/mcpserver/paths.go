package mcpserver

import (
	"path"
	"strings"
)

// matchPath reports whether the cleaned absolute slash path p matches pat. A
// "**" segment matches any number of path segments, including none; other
// segments use path.Match syntax ("*", "?", "[...]") within one segment.
func matchPath(pat, p string) bool {
	return matchSegs(splitPath(pat), splitPath(p))
}

func splitPath(p string) []string {
	p = strings.Trim(p, "/")
	if p == "" {
		return nil
	}
	return strings.Split(p, "/")
}

func matchSegs(pat, segs []string) bool {
	for len(pat) > 0 {
		if pat[0] == "**" {
			if len(pat) == 1 {
				return true
			}
			for i := 0; i <= len(segs); i++ {
				if matchSegs(pat[1:], segs[i:]) {
					return true
				}
			}
			return false
		}
		if len(segs) == 0 {
			return false
		}
		if ok, err := path.Match(pat[0], segs[0]); err != nil || !ok {
			return false
		}
		pat, segs = pat[1:], segs[1:]
	}
	return len(segs) == 0
}
